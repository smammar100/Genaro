#!/usr/bin/env node
/**
 * Writes the Storybook Foundations pages (colour, spacing, radius and
 * elevation, icons) from styles/tokens.json and icons.ts. Every token, value
 * and usage note is written into the MDX as text, so people reading the page
 * and agents reading Storybook's docs manifest get the same facts.
 *
 *   node src/components/genaro/tools/foundations.mjs
 *
 * Re-run it whenever tokens.json or icons.ts changes.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const kit = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(kit, "stories", "foundations");
const tokens = JSON.parse(fs.readFileSync(path.join(kit, "styles", "tokens.json"), "utf8"));

/** A JSX attribute value: quotes and braces can't break the MDX. */
const attr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/\{/g, "&#123;").replace(/\}/g, "&#125;");
/** Token references ("{gray-6}") read as plain names. */
const ref = (v) => String(v).replace(/\{([^}]+)\}/g, "$1");

const header = (title, summary) =>
  `{/* Generated by src/components/genaro/tools/foundations.mjs from styles/tokens.json — edit the generator or the tokens, not this file. */}\n` +
  `import { Meta } from "@storybook/addon-docs/blocks";\n` +
  `import { Ramp, TokenRow, TokenTable } from "./blocks";\n\n` +
  `<Meta title="${title}" summary="${attr(summary)}" />\n\n`;

const row = (kind, t) => {
  const name = `--${t.name}`;
  const v = t.value;
  const [light, dark] = typeof v === "object" && v !== null ? [ref(v.light), ref(v.dark)] : [ref(v), undefined];
  return `<TokenRow kind="${kind}" token="${name}" value="${attr(light)}"${dark && dark !== light ? ` dark="${attr(dark)}"` : ""} usage="${attr(t.usage ?? "")}" />`;
};

const table = (kind, list, preview) =>
  `<TokenTable${preview ? ` preview="${preview}"` : ""}>\n${list.map((t) => "  " + row(kind, t)).join("\n")}\n</TokenTable>\n`;

// ---------------------------------------------------------------- Colour
{
  const all = tokens.color.tokens;
  const PRIMITIVE = /^(gray|azure|blue|cyan|green|lime|magenta|orange|purple|red|rose|teal|yellow|black-alpha)-\d+$/;
  const semantic = all.filter((t) => !PRIMITIVE.test(t.name));
  const ramps = [...new Set(all.filter((t) => PRIMITIVE.test(t.name)).map((t) => t.name.replace(/-\d+$/, "")))];
  const group = (test) => semantic.filter((t) => test(t.name));
  const groups = [
    ["Backgrounds and surfaces", "Page, card and raised surfaces (`--bg`, `--bg-surface*`).", (n) => n === "bg" || n.startsWith("bg-surface")],
    ["Fills", "Filled controls and status fills: buttons, badges, toggles (`--bg-fill*`).", (n) => n.startsWith("bg-fill")],
    ["Other backgrounds", "Inverse chrome and the rest of the `--bg-*` set.", (n) => n.startsWith("bg-") && !n.startsWith("bg-surface") && !n.startsWith("bg-fill")],
    ["Text", "Two text colours carry hierarchy: `--text` and `--text-secondary`. The tones are for status only.", (n) => n.startsWith("text")],
    ["Icons", "Icon ink: `--icon` by default, `--icon-secondary` beside secondary text.", (n) => n.startsWith("icon")],
    ["Borders", "Dividers, outlines and focus rings.", (n) => n.startsWith("border")],
    ["Components", "Tokens a single component owns: inputs, navigation, avatars, video thumbnails, checkboxes, radios, the modal backdrop.", (n) => !/^(bg|text|icon|border)/.test(n)],
  ];
  let mdx = header("Foundations/Colour", "Semantic colour tokens (light and dark values, what each is for) and the primitive ramps behind them. Style UI only with semantic tokens: no hex, no Tailwind palette, no dark: overrides.");
  mdx += `# Colour\n\nStyle UI with **semantic tokens only**: \`var(--bg-surface)\` in CSS, \`bg-(--bg-surface)\` and \`text-(--text-secondary)\` in Tailwind. No hex values, no Tailwind palette colours, no \`dark:\` overrides: the light and dark themes swap every token at once (\`.dark\` on \`<html>\`; use the Theme switch in the toolbar). The one exception is registration-plate yellow (\`bg-plate\`).\n\nText uses two colours, \`--text\` and \`--text-secondary\`, and never fades with opacity. Tone colours (critical, success, warning, caution, info) are for status only.\n\n`;
  for (const [title, intro, test] of groups) {
    const list = group(test);
    if (list.length) mdx += `## ${title}\n\n${intro}\n\n${table("color", list)}\n`;
  }
  mdx += `## Primitive ramps\n\nThe 16-step ramps every semantic token points at (${ramps.map((r) => `\`${r}\``).join(", ")}). Never use a primitive in UI; pick the semantic token that says what the colour is for.\n\n${ramps.map((r) => `<Ramp name="${r}" steps={${all.filter((t) => t.name.startsWith(r + "-") && PRIMITIVE.test(t.name)).length}} />`).join("\n")}\n`;
  fs.writeFileSync(path.join(out, "Colour.mdx"), mdx);
}

// ---------------------------------------------------------------- Spacing
{
  let mdx = header("Foundations/Spacing", "The space-* scale (4px base) with what each step is for. Use Tailwind's scale (p-4 = space-400) or var(--space-*); never hard-code px.");
  mdx += `# Spacing\n\nA 4px-based scale. In Tailwind, use the spacing scale (\`p-4\` is \`--space-400\`, 16px); in CSS, \`var(--space-*)\`. Never hard-code pixels.\n\n${table("space", tokens.spacing.tokens, "Size")}`;
  fs.writeFileSync(path.join(out, "Spacing.mdx"), mdx);
}

// ---------------------------------------------------------------- Radius, borders and elevation
{
  let mdx = header("Foundations/Radius and elevation", "Corner radii, border widths and the shadow-* elevation scale, with light and dark values and what each is for.");
  mdx += `# Radius and elevation\n\nCorners, border widths and shadows come from tokens: \`rounded-(--radius-300)\`, \`var(--border-width-025)\`, \`shadow-(--shadow-100)\`. Shadows also swap with the theme.\n\n## Radius\n\n${table("radius", tokens.radius.tokens)}\n## Border widths\n\n${table("border", tokens.borderWidth.tokens)}\n## Elevation\n\n${table("shadow", tokens.shadow.tokens)}`;
  fs.writeFileSync(path.join(out, "RadiusAndElevation.mdx"), mdx);
}

// ---------------------------------------------------------------- Icons
{
  const src = fs.readFileSync(path.join(kit, "icons.ts"), "utf8");
  const names = [...src.matchAll(/^\s+([A-Z][A-Za-z]+(?:Major|Minor)):/gm)].map((m) => m[1]);
  let mdx = `{/* Generated by src/components/genaro/tools/foundations.mjs from icons.ts — edit the generator or the icons, not this file. */}\n`;
  mdx += `import { Meta } from "@storybook/addon-docs/blocks";\nimport { Icon } from "../../Icon";\n\n`;
  mdx += `<Meta title="Foundations/Icons" summary="${attr(`The ${names.length} Genaro icons by name, for the icon/source props (Major = 20px glyphs for navigation and headers, Minor = compact glyphs for buttons and inline use).`)}" />\n\n`;
  mdx += `# Icons\n\nPass a name to any \`icon\` or \`source\` prop (\`<Button icon="PlusMinor">\`, \`<Icon source="SearchMinor" />\`). Icons ink with \`currentColor\`, so they follow the text or the \`tone\` they sit in. Any React element works too, such as a lucide-react icon, when the kit has no glyph for the idea.\n\n`;
  mdx += `<div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fill, minmax(160px, 1fr))", gap: "var(--space-200)" }}>\n`;
  mdx += names.map((n) => `  <div style={{ display: "flex", alignItems: "center", gap: "var(--space-200)" }}><Icon source="${n}" /><code>${n}</code></div>`).join("\n");
  mdx += `\n</div>\n`;
  fs.writeFileSync(path.join(out, "Icons.mdx"), mdx);
}

console.log("Foundations written to", path.relative(process.cwd(), out));
